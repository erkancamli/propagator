// Build: copy public/ to dist/ with content hashed CSS, JS and share image, then write
// lib/manifest.mjs (asset names for the renderer) and lib/seed.mjs (bundled seed issues).
import { readFile, writeFile, mkdir, rm, cp, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const hash = (b) => createHash('sha256').update(b).digest('hex').slice(0, 10);
await rm('dist', { recursive: true, force: true });
await mkdir('dist/assets', { recursive: true });
await cp('public', 'dist', { recursive: true });
const assets = {};
// self hosted fonts (SIL Open Font License) are inlined at the top of the stylesheet
await writeFile('dist/assets/site.css', (await readFile('public/assets/fonts.css', 'utf8')) + (await readFile('public/assets/site.css', 'utf8')));
for (const [key, src, ext] of [['css', 'assets/site.css', 'css'], ['js', 'assets/site.js', 'js'], ['theme', 'assets/theme.js', 'js'], ['og', 'og.png', 'png']]) {
  const buf = await readFile((key === 'css' ? 'dist/' : 'public/') + src);
  const name = src.replace(/\.[a-z]+$/, `-${hash(buf)}.${ext}`);
  await writeFile('dist/' + name, buf);
  assets[key] = name;
}
await writeFile('lib/manifest.mjs', `// generated by scripts/build.mjs\nexport const ASSETS = ${JSON.stringify(assets, null, 2)};\n`);
const seed = { weekly: [], daily: [] };
for (const f of (await readdir('content/seed')).sort()) {
  if (!f.endsWith('.json')) continue;
  const x = JSON.parse(await readFile('content/seed/' + f, 'utf8'));
  seed[x.kind].push(x);
}
// role calls from #role-announcements, one file per announcement
seed.rolecalls = [];
for (const f of (await readdir('content/roles')).filter((f) => f.endsWith('.json')).sort()) seed.rolecalls.push(JSON.parse(await readFile('content/roles/' + f, 'utf8')));
await writeFile('lib/seed.mjs', `// generated by scripts/build.mjs from content/seed and content/roles, do not edit\nexport const SEED = ${JSON.stringify(seed)};\n`);
const tm = {};
for (const f of (await readdir('content/tm')).sort()) if (/^[a-z]{2,3}\.json$/.test(f)) tm[f.slice(0, -5)] = JSON.parse(await readFile('content/tm/' + f, 'utf8'));
await writeFile('lib/tm.mjs', `// generated by scripts/build.mjs from content/tm, do not edit\nexport const TM = ${JSON.stringify(tm)};\n`);
console.log('built', assets, `languages: ${Object.keys(tm).join(', ')}`, `seed: ${seed.weekly.length} weekly, ${seed.rolecalls.length} role calls`);
